package org.shauryabahl08.oops.class_and_object;

// This is a student template
public class Student { // we are creating a public student template
    // Characteristics
    String name; // every student has a name
    int age; // every student has an age
    int rollNumber; // every student has a roll number
    String address; // every student has an address

    // behaviour
    void study() { // every student can study
        System.out.println("Student is studying");
    }

    void play() { // every student can study
        System.out.println("Student is playing");
    }
}
